/**
 * Заменить непереводимые куски метками ⟦0⟧, ⟦1⟧ …
 * Возвращает { masked, map }.
 *
 * Метки выбраны так, чтобы переводчик их не трогал и не переносил:
 * редкие символы + число.
 */
export function protect(text) {
  if (typeof text !== "string" || !text) return { masked: text, map: [] };

  const map = [];
  let masked = text;

  const put = (match) => {
    // один и тот же термин — одна и та же метка
    const existing = map.indexOf(match);
    const i = existing >= 0 ? existing : map.push(match) - 1;
    return `⟦${i}⟧`;
  };

  // сначала точные термины (длинные раньше коротких)
  for (const term of [...PROTECTED].sort((a, b) => b.length - a.length)) {
    // экранируем спецсимволы регулярного выражения
    const esc = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // границы слова работают плохо с точками и дефисами — проверяем вручную
    const re = new RegExp(`(^|[^\\p{L}\\p{N}_-])(${esc})(?![\\p{L}\\p{N}_-])`, "giu");
    masked = masked.replace(re, (_m, pre, hit) => pre + put(hit));
  }

  // затем шаблоны (единицы измерения, коды, проценты)
  for (const re of PROTECTED_PATTERNS) {
    masked = masked.replace(re, (hit) => put(hit));
  }

  return { masked, map };
}

/** Вернуть настоящие термины на место меток */
export function restore(text, map) {
  if (typeof text !== "string" || !map?.length) return text;
  let out = text;
  map.forEach((value, i) => {
    // переводчик может исказить метку: ⟦ 0 ⟧, [0], （0）, 【0】
    const variants = [
      `⟦${i}⟧`, `⟦ ${i} ⟧`, `⟦${i} ⟧`, `⟦ ${i}⟧`,
      `〔${i}〕`, `【${i}】`, `[${i}]`, `［${i}］`, `（${i}）`, `(${i})`, `{${i}}`,
    ];
    for (const v of variants) {
      out = out.split(v).join(value);
    }
  });
  // если метка всё же осталась испорченной — убираем скобки, оставив число
  return out.replace(/⟦\s*(\d+)\s*⟧/g, (m, i) => map[Number(i)] ?? m);
}

/** Короткая шпаргалка по терминам для инструкции переводчику */
export function glossaryHint(to) {
  const g = GLOSSARY[to];
  if (!g) return "";
  return Object.entries(g)
    .map(([ru, tr]) => `  • ${ru} → ${tr}`)
    .join("\n");
}
