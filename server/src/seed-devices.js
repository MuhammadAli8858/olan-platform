/**
 * Собрать карточку прибора для конкретного решения.
 * base — ключ в BASE, extra — акценты именно для этой задачи.
 */
function device(baseKey, extra) {
  const b = BASE[baseKey];
  return {
    id: `${baseKey}-${extra.slug}`,
    baseKey,
    name: b.name,
    tagline: extra.tagline || b.tagline,
    icon: b.icon,
    badge: extra.badge || "",
    summary: extra.summary,
    highlights: extra.highlights,
    description: extra.description || b.description,
    specs: extra.specs || b.specs,
    features: b.features,
    photos: b.photos,
    priceNote: PRICE_NOTE,
  };
}

