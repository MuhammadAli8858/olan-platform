/** Подмешать каталог и обновлённые тексты в русское наполнение */
export function applyDevices(ru) {
  for (const [id, devices] of Object.entries(DEVICES)) {
    const sol = ru.solutions?.[id];
    if (!sol) continue;
    sol.devices = structuredClone(devices);
    const copy = SOLUTION_COPY[id];
    if (copy) Object.assign(sol, copy);
  }
  return ru;
}
