/**
 * Готовые переводы главного экрана, описания компании и названий
 * проблем на 8 языков. Остальной текст (подробные страницы решений)
 * пока копируется с русского — его можно перевести в админ-панели
 * или включить автоперевод в config.js.
 */
import TR from "./seed-translations.json" with { type: "json" };

export function seedContent() {
  const content = { ru: RU };

  for (const lang of LANGS) {
    if (lang === "ru") continue;

    // берём русскую версию как основу — структура одинакова для всех языков
    const c = JSON.parse(JSON.stringify(RU));

    // подставляем переводы главного экрана
    c.hero.badge = TR.hero.badge[lang] ?? c.hero.badge;
    c.hero.titleLine1 = TR.hero.titleLine1[lang] ?? c.hero.titleLine1;
    c.hero.titleAccent = TR.hero.titleAccent[lang] ?? c.hero.titleAccent;
    c.hero.titleLine3 = TR.hero.titleLine3[lang] ?? c.hero.titleLine3;
    c.hero.lead = TR.hero.lead[lang] ?? c.hero.lead;

    // описание компании и строка статуса
    c.company.about = TR.company_about[lang] ?? c.company.about;
    c.company.statusLine = TR.company_status[lang] ?? c.company.statusLine;

    // названия и описания восьми проблем
    c.problems = c.problems.map((p) => {
      const tr = TR.problems[p.code];
      if (!tr) return p;
      return {
        ...p,
        title: tr.t[lang] ?? p.title,
        short: tr.s[lang] ?? p.short,
      };
    });

    // заголовки страниц решений берём из названий проблем,
    // чтобы посетитель видел перевод, а не русский текст
    for (const p of c.problems) {
      const sol = c.solutions[p.id];
      if (sol) sol.heroRest = p.title;
      if (sol) sol.heroAccent = "";
    }

    content[lang] = c;
  }

  return content;
}
