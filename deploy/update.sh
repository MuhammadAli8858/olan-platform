#!/bin/bash
# ══════════════════════════════════════════════════════════════════
# ОБНОВЛЕНИЕ ПЛАТФОРМЫ
# Пересобирает и перезапускает всё. Данные не теряются —
# база и логотипы лежат в папке data/ и подключаются томами.
# ══════════════════════════════════════════════════════════════════
set -e
cd "$(dirname "$0")/.."

echo "▶ Резервная копия перед обновлением…"
./deploy/backup.sh || true

echo "▶ Пересборка…"
docker compose build

echo "▶ Перезапуск…"
docker compose up -d

echo "▶ Состояние:"
docker compose ps
echo ""
echo "✅ Обновление завершено"
